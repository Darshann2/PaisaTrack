export const CURRENCY_MAP = new Map<string, CurrencyInfo>(
  WORLD_CURRENCIES.map((c) => [c.code.toUpperCase(), c])
);

export const DEFAULT_CURRENCY_CODE = 'INR';

/**
 * Returns CurrencyInfo for any ISO code, or a safe fallback
 */
export function getCurrencyInfo(code?: string): CurrencyInfo {
  if (!code) return CURRENCY_MAP.get(DEFAULT_CURRENCY_CODE)!;
  const upper = code.trim().toUpperCase();
  const found = CURRENCY_MAP.get(upper);
  if (found) return found;

  // Safe dynamic fallback for non-standard or custom codes
  return {
    code: upper,
    name: upper,
    symbol: upper,
    disambiguatedSymbol: upper,
    decimals: 2,
    defaultLocale: 'en-US',
    country: 'International',
    flag: '🌐',
  };
}

/**
 * Search currencies by keyword across code, name, symbol, or country
 */
export function searchCurrencies(query: string): CurrencyInfo[] {
  const q = query.trim().toLowerCase();
  if (!q) return WORLD_CURRENCIES;

  return WORLD_CURRENCIES.filter(
    (c) =>
      c.code.toLowerCase().includes(q) ||
      c.name.toLowerCase().includes(q) ||
      c.symbol.toLowerCase().includes(q) ||
      c.country.toLowerCase().includes(q)
  );
}

/**
 * Get popular/major currencies for quick selection
 */
export function getMajorCurrencies(): CurrencyInfo[] {
  return WORLD_CURRENCIES.filter((c) => c.isMajor);
}

